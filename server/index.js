import express from 'express';
import cors from 'cors';
import { runHostDiagnostic } from './probes/windowsProbe.js';
import { safeLog } from './utils/sanitize.js';

const app = express();
const PORT = process.env.PORT || 4820;
const HOST = '127.0.0.1'; // Strictly loopback only

// Restrict CORS to local web UI
app.use(cors({
  origin: [
    'http://localhost:5180',
    'http://127.0.0.1:5180',
    'http://localhost:5173',
    'http://127.0.0.1:5173'
  ],
  methods: ['GET', 'POST'],
}));

app.use(express.json({ limit: '5mb' }));

// Health Check
app.get('/api/health', (req, res) => {
  res.json({
    status: 'healthy',
    version: '1.0.0',
    platform: process.platform,
    isWindows: process.platform === 'win32',
    nodeVersion: process.version,
    loopbackOnly: true,
    timestamp: new Date().toISOString(),
  });
});

// Run Host Diagnostic (Windows & Office)
app.get('/api/diagnostics/host', async (req, res) => {
  if (process.platform !== 'win32') {
    return res.status(400).json({
      error: 'Host device diagnostics are only supported on Windows OS.',
      recommendation: 'Run Invoke-LicenseDiagnostic.ps1 on your Windows machine and import the resulting JSON file.',
    });
  }

  try {
    safeLog('[Diagnostic Server] Initiating authenticated read-only host license probe...');
    const result = await runHostDiagnostic();
    safeLog('[Diagnostic Server] Host diagnostic probe completed successfully.');
    res.json(result);
  } catch (err) {
    safeLog('[Diagnostic Server] Probe execution error:', err.message);
    res.status(500).json({
      error: 'Failed to inspect host licensing state',
      details: err.message,
    });
  }
});

// Validate & Ingest Offline Diagnostic JSON File
app.post('/api/diagnostics/import', (req, res) => {
  const payload = req.body;
  if (!payload || !payload.windowsLicense || !payload.hostname) {
    return res.status(400).json({
      error: 'Invalid diagnostic file schema. Expected a report generated by Invoke-LicenseDiagnostic.ps1.',
    });
  }

  // Ensure keys in payload are safely formatted
  if (payload.windowsLicense && payload.windowsLicense.partialKey) {
    payload.windowsLicense.partialKey = String(payload.windowsLicense.partialKey).slice(-5);
  }

  res.json({
    message: 'Diagnostic report imported successfully',
    report: payload,
  });
});

app.listen(PORT, HOST, () => {
  safeLog(`[Microsoft License Inspector] Diagnostic Service active on http://${HOST}:${PORT}`);
  safeLog(`[Security] Strictly bound to loopback interface. Zero remote ingress.`);
});
